const perCourse = {};
for (const f of readdirSync(DATA).filter((x) => x.endsWith(".js") && !x.startsWith("_")).sort()) {
  const win = {};
  win.window = win; win.COURSE_PACKS = [];
  try { new Function("window", "self", "globalThis", readFileSync(join(DATA, f), "utf8"))(win, win, win); } catch { continue; }
  const c = win.COURSE_PACKS[0];
  const text = JSON.stringify(c);
  CORPUS += text + "\n";
  perCourse[c.title] = text;
}

