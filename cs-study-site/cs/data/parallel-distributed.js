 md: "**Amdahl 定律（1967）** 假设问题规模固定（强扩展，strong scaling）：$T(N) = s \\cdot T_1 + (1 - s) \\cdot T_1 / N$，于是 $S(N) = \\frac{1}{s + (1 - s)/N}$，上限是 $1 / s$。它回答的是「同样大的活，加核能快多少」。核数 $\\to \\infty$ 时，加速比被串行部分锁死。\n\n**Gustafson 定律（1988）** 换了一个提问方式：现实中人们加机器往往是为了做更大的活，而不是把同样的活做得更快（弱扩展，weak scaling）。设并行执行时串行部分占实际总时间的比例为 $s$，则 $S = s + N \\times (1 - s)$。$s = 5\\%$、$N = 64$ 时，$S = 0.05 + 64 \\times 0.95 = 60.85$ —— 同一个程序，Amdahl 只给 15.42，Gustafson 给 60.85。**两个定律不矛盾，它们回答的是不同问题**：Amdahl 算「固定工作量下的延迟缩短」，Gustafson 算「固定时间预算下能完成多少工作量」。\n\n由此得到两个工程术语：\n\n- 强扩展（strong scaling）：问题规模固定，测 $S(N)$ 与效率 $E(N) = S(N) / N$。效率随 $N$ 下降是常态。\n- 弱扩展（weak scaling）：每核负载固定，问题规模随 $N$ 同比放大，测 $T(N) / T(1)$，理想值是 1。超算榜单（TOP500）用 HPL 测的就是强扩展，而气候、流体这类应用更关心弱扩展。\n\n**并行开销（parallel overhead）** 是让实测曲线低于理论曲线的元凶，主要有四类：\n\n1. 通信开销：数据必须跨核/跨机搬运，网络往返常是微秒级，比一次 L1 命中贵 3 个数量级。\n2. 同步开销：锁、屏障（barrier）、原子操作，都会让快线程等慢线程，等待期是纯浪费。\n3. 负载不均（load imbalance）：最慢的那个线程决定结束时间，其余线程干完就闲着。\n4. 额外工作：冗余计算、数据复制、任务创建与调度。\n\n**并行粒度（granularity）与任务划分** 就是在开销与均衡之间取平衡：\n\n- 粗粒度：任务少而大，通信/调度开销小，但容易出现负载不均、无法充分利用所有核。\n- 细粒度：任务多而小，负载均衡好，但每次任务的调度与通信开销会吃掉收益。经验判据是「**每次任务的通信与调度时间应小于其计算时间的 $\\frac{1}{10}$**」。\n\n具体划分策略有三类：按数据划分（data partition，把数组切片分给各核，最常用）、按功能划分（task/function partition，不同核做不同的事，如一个算、一个压缩）、流水线划分（pipeline，阶段串联，吞吐换延迟）。举例：10000 个元素，若每个元素建一个任务、每次任务开销 5 μs，光调度就要 $10000 \\times 5\\ \\mu\\text{s} = 50\\ \\text{ms}$；改成每 250 个一组，只建 40 个任务，调度开销降到 0.2 ms —— 这就是粒度选择的价值。"
