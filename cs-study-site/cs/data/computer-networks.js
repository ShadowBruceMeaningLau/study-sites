 md: "**距离向量（Distance Vector, DV）**的核心思想：每个路由器只知道自己到邻居的「代价」，并周期性把自己的整张距离向量（到所有目的网络的代价）告诉邻居；收到邻居的向量后，按 Bellman-Ford 方程更新：\\n $$ D_x(y) = \\min_v \\{\\, c(x,v) + D_v(y) \\,\\} $$\n\n**RIP（Routing Information Protocol）**：以跳数（hop count）为度量，**最大 $15$ 跳，$16$ 表示不可达**，因此只适合小型网络（直径受限）。每 30 秒向邻居广播（RIPv1）或组播（RIPv2）整张路由表，180 秒未收到则认为邻居失效。RIP 简单、开销小，但收敛慢。\n\n**坏消息传得慢（count-to-infinity）** 的经典场景：A—B—C 串联，A 到网络 N 的距离是 1，B 通过 A 学到 2。此时 A—N 的链路断了，A 把自己的距离改为 16，但 B 恰好先把自己的向量（到 N 为 $2$）发给 A，A 便误以为「经 B 到 N 只要 $2 + 1 = 3$」，于是更新为 $3$；A 再告诉 B「我到 N 是 $3$」，B 改成 $4$……如此反复递增，直到都变成 $16$ 才发现不可达。\n\n**缓解手段**：\n- **定义最大值**：RIP 用 $16$ 当无穷大，把无穷次迭代压缩到有限次（跳数上限小的另一个好处）。\n- **水平分割（split horizon）**：不把从某接口学到的路由再从该接口发回去，直接切断「互相告知」的环路。\n- **毒性逆转（poison reverse）**：把从某接口学到的路由再从该接口发回时，代价标为 $16$（不可达），比水平分割更明确。\n- **触发更新（triggered update）**：拓扑变化立即发送更新，不等 30 秒周期。\n\n这些手段能缓解但不能根除计数到无穷，根本原因是 DV 算法只有「邻居的二手信息」，不知道全局拓扑。"
